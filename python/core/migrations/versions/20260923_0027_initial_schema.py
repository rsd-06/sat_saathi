def _enable_postgis() -> None:
    """Make sure PostGIS exists before the first geometry column needs it.

    This migration always required PostGIS and never said so. It worked only
    because the compose image ships with the extension already enabled; on a
    fresh database — Supabase, RDS, a plain Postgres — the first geometry
    column failed.

    Where an `extensions` schema exists (Supabase's convention, and on its
    search_path) the extension goes there; otherwise it takes the default.
    IF NOT EXISTS keeps this a no-op on databases that already have it,
    whichever schema it lives in.
    """
    bind = op.get_bind()
    has_schema = bind.execute(
        sa.text("SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'extensions')")
    ).scalar_one()
    if has_schema:
        op.execute("CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions")
    else:
        op.execute("CREATE EXTENSION IF NOT EXISTS postgis")


